import { RoadmapResponse } from "../types";
// @ts-ignore
import html2pdf from 'html2pdf.js';

export const generateMarkdown = (roadmap: RoadmapResponse): string => {
  let md = `# Learning Path: ${roadmap.field}\n\n`;
  md += `> ${roadmap.overview}\n\n`;
  md += `## Roadmap Overview\n\n`;

  roadmap.steps.forEach((step, index) => {
    md += `### ${index + 1}. ${step.title}\n`;
    md += `**Level:** ${step.level} | **Duration:** ${step.duration}\n\n`;
    md += `${step.description}\n\n`;
    
    md += `**Key Concepts:**\n`;
    step.keyConcepts.forEach(c => md += `- ${c}\n`);
    md += `\n`;

    md += `**Recommended Projects:**\n`;
    step.recommendedProjects.forEach(p => md += `- ${p}\n`);
    md += `\n`;
    
    md += `**Search Terms:**\n`;
    step.searchTerms.forEach(t => md += `- ${t}\n`);
    md += `\n---\n\n`;
  });

  md += `\nGenerated by SkillPath AI`;
  return md;
};

export const downloadMarkdown = (roadmap: RoadmapResponse) => {
  const md = generateMarkdown(roadmap);
  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${roadmap.field.toLowerCase().replace(/\s+/g, '-')}-roadmap.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
};

export const downloadPDF = (element: HTMLElement, roadmap: RoadmapResponse) => {
  const opt = {
    margin: [10, 10, 10, 10],
    filename: `${roadmap.field.toLowerCase().replace(/\s+/g, '-')}-roadmap.pdf`,
    image: { type: 'jpeg', quality: 0.98 },
    html2canvas: { scale: 2, useCORS: true, letterRendering: true, scrollY: 0 },
    jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' },
    pagebreak: { mode: ['css', 'legacy'] }
  };

  // We clone the element to ensure we can manipulate it if needed (e.g. forcing light mode)
  // But for now, direct export is fine.
  html2pdf().set(opt).from(element).save();
};